# frozen_string_literal: true

module Websites
  # What a dealer can do about their own site, in plain words, and nothing else.
  #
  # Tom, 2026-11-03: technical scan results are for prospecting. Showing them to a
  # customer read as a list of faults in a site we built and run, most of which
  # are ours to look after or not faults at all. Each item here is something only
  # the dealer can supply, so anything on the list really is theirs to act on.
  #
  # Read from the site's own records where they exist, because those are certain;
  # the page checks come from the audit report, limited to copy the dealer writes.
  class SeoActionList
    # Audit check => what to tell the dealer. Everything else in the audit is
    # either generated by us or a matter of how the platform serves the site.
    PAGE_ACTIONS = {
      'titles' => ['Write a better page title', 'Google shows the title in search results, and a clear one gets more clicks.'],
      'descriptions' => ['Write a page description', 'This is the short summary Google shows under your title.'],
      'headings' => ['Fix the main heading', 'Each page should have one main heading that says what the page is about.'],
      'thin_content' => ['Add more text', 'Pages with very little text rarely show up in search.'],
      'image_alt' => ['Describe your images', 'A short description helps search engines and people using screen readers.']
    }.freeze

    def initialize(website:, report: nil)
      @website = website
      @report = report
    end

    def call
      [analytics_item, conversion_item, prices_item, *page_items].compact
    end

    private

    def company = @website.company

    def tags = @tags ||= TrackingTags.new(website: @website)

    def analytics_item
      return nil if tags.analytics_installed?

      item('analytics', 'Add Google Analytics',
           'It shows where your visitors come from and what they look at. It is free. Create a property at ' \
           'analytics.google.com, then enter the Measurement ID, which starts with G-.',
           'Add it', :website_settings)
    end

    # Only for a dealer who advertises on Google: nobody else has a label to find.
    def conversion_item
      return nil if tags.google_ads_id.blank? || tags.google_ads_lead_label.present?

      item('google_ads_conversion', 'Add your Google Ads conversion label',
           'Your Google Ads tag is on the site, but Google is not told when someone sends in a form, so your ' \
           'ads cannot learn which clicks turn into leads. Whoever runs your ads can give you the label.',
           'Add it', :conversion_settings)
    end

    def prices_item
      return nil if company.nil?

      missing = company.vehicles.where(is_deleted: [false, nil], status: HomeUrl::SERVABLE_STATUSES)
                       .where('sale_price IS NULL OR sale_price <= 0').count
      return nil if missing.zero?

      item('home_prices', "Add prices to #{missing} #{'home'.pluralize(missing)}",
           'Google can only show a price and availability for a home that has a price. Leave it off if you ' \
           'prefer not to publish prices. Your site still works, and those homes just show up without one.',
           'Open inventory', :inventory, count: missing)
    end

    # Pages only. Home pages are generated from the listing, so they are not
    # something the dealer edits as a page.
    def page_items
      Array(@report && @report['checks']).filter_map do |check|
        action = PAGE_ACTIONS[check['key'].to_s]
        next if action.nil? || check['status'] == 'pass'

        urls = Array(check['urls']).reject { |url| HomeUrl.matches?(URI.parse(url.to_s).path.to_s) }
        next if urls.empty?

        item(check['key'].to_s, "#{action[0]} on #{urls.size} #{'page'.pluralize(urls.size)}", action[1],
             'Edit pages', :pages, count: urls.size, urls: urls)
      rescue URI::InvalidURIError
        nil
      end
    end

    def item(key, title, detail, action_label, action, count: nil, urls: [])
      { key: key, title: title, detail: detail, action_label: action_label, action: action.to_s, count: count, urls: urls }
    end
  end
end
